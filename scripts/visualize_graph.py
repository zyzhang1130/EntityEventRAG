#!/usr/bin/env python3
"""Graph Visualization Script for Entity-Event RAG.

This script provides 2D and 3D visualization of knowledge graphs
generated by the Entity-Event RAG system.
"""

import os
import sys
import argparse
import webbrowser
import hashlib
from pathlib import Path

import networkx as nx
from pyvis.network import Network
import plotly.graph_objects as go


def get_color_for_id(id_string: str) -> str:
    """Generate a consistent color based on an ID string."""
    return f"#{hashlib.md5(str(id_string).encode()).hexdigest()[:6]}"


def visualize_graph_2d(
    G: nx.Graph,
    output_path: str,
    title: str = "Entity-Event Knowledge Graph",
    entity_color: str = "#FF5733",
    event_color: str = "#33C1FF"
) -> str:
    """Create 2D visualization using Pyvis.
    
    Args:
        G: NetworkX graph
        output_path: Path to save HTML output
        title: Graph title
        entity_color: Color for entity nodes
        event_color: Color for event nodes
    
    Returns:
        Path to the saved HTML file
    """
    net = Network(
        height="750px",
        width="100%",
        bgcolor="#ffffff",
        font_color="black",
        directed=True
    )
    
    net.set_options("""
    {
      "physics": {
        "enabled": true,
        "solver": "forceAtlas2Based",
        "forceAtlas2Based": {
          "gravitationalConstant": -50,
          "centralGravity": 0.01,
          "springLength": 100,
          "springConstant": 0.08,
          "avoidOverlap": 1.0
        },
        "minVelocity": 0.01
      }
    }
    """)
    
    # Determine node colors based on entity_type
    for node in G.nodes():
        node_data = G.nodes[node]
        entity_type = node_data.get('entity_type', '').lower()
        
        # Check if it's an event type node
        is_event = entity_type in ['event', 'battle', 'discovery', 'meeting', 
                                    'journey', 'transformation', 'conflict']
        color = event_color if is_event else entity_color
        
        description = node_data.get('description', 'No description')
        title_text = f"Node: {node}<br>Type: {entity_type}<br>Description: {description}"
        
        net.add_node(node, title=title_text, color=color, label=str(node)[:20])
    
    # Add edges
    for edge in G.edges(data=True):
        source, target = edge[0], edge[1]
        edge_data = edge[2]
        
        relationship = edge_data.get('keywords', '').strip('"') if 'keywords' in edge_data else 'unknown'
        weight = edge_data.get('weight', 'N/A')
        description = edge_data.get('description', 'No description').strip('"')
        title_text = f"Relationship: {relationship}<br>Weight: {weight}<br>Description: {description}"
        
        net.add_edge(source, target, title=title_text, color='gray')
    
    # Save to HTML
    net.write_html(output_path)
    
    # Add legend
    legend_html = f"""
    <div id='legend'>
        <h3>{title}</h3>
        <p><span style='color:{entity_color};'>&#9679;</span> Entities</p>
        <p><span style='color:{event_color};'>&#9679;</span> Events</p>
    </div>
    """
    
    custom_style = """
    <style>
    #legend {
        position: fixed;
        top: 10px;
        left: 10px;
        z-index: 999;
        background: white;
        padding: 10px;
        border: 1px solid #ccc;
        border-radius: 4px;
        font-size: 12px;
        opacity: 0.9;
    }
    </style>
    """
    
    with open(output_path, 'r', encoding='utf-8') as f:
        content = f.read()
    content = content.replace('<body>', f'<body>{custom_style}{legend_html}')
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(content)
    
    return output_path


def visualize_graph_3d(
    G: nx.Graph,
    output_path: str,
    title: str = "Entity-Event Knowledge Graph (3D)",
    entity_color: str = "#FF5733",
    event_color: str = "#33C1FF"
) -> str:
    """Create 3D visualization using Plotly.
    
    Args:
        G: NetworkX graph
        output_path: Path to save HTML output
        title: Graph title
        entity_color: Color for entity nodes
        event_color: Color for event nodes
    
    Returns:
        Path to the saved HTML file
    """
    pos = nx.spring_layout(G, dim=3, seed=42)
    
    # Build node colors and positions
    node_x, node_y, node_z = [], [], []
    node_colors_list = []
    node_texts = []
    
    for node in G.nodes():
        node_data = G.nodes[node]
        entity_type = node_data.get('entity_type', '').lower()
        
        is_event = entity_type in ['event', 'battle', 'discovery', 'meeting',
                                    'journey', 'transformation', 'conflict']
        color = event_color if is_event else entity_color
        
        node_x.append(pos[node][0])
        node_y.append(pos[node][1])
        node_z.append(pos[node][2])
        node_colors_list.append(color)
        
        description = node_data.get('description', 'No description')
        node_texts.append(f"Node: {node}<br>Type: {entity_type}<br>Description: {description}")
    
    # Create node trace
    node_trace = go.Scatter3d(
        x=node_x, y=node_y, z=node_z,
        mode='markers+text',
        marker=dict(size=5, color=node_colors_list, line=dict(width=1, color='white')),
        text=[str(n)[:15] for n in G.nodes()],
        textposition='top center',
        hovertext=node_texts,
        hoverinfo='text'
    )
    
    # Create edge traces
    edge_traces = []
    for edge in G.edges():
        x0, y0, z0 = pos[edge[0]]
        x1, y1, z1 = pos[edge[1]]
        
        edge_trace = go.Scatter3d(
            x=[x0, x1], y=[y0, y1], z=[z0, z1],
            mode='lines',
            line=dict(width=2, color='gray'),
            hoverinfo='none'
        )
        edge_traces.append(edge_trace)
    
    # Create figure
    fig = go.Figure(data=[*edge_traces, node_trace])
    fig.update_layout(
        title=title,
        showlegend=False,
        margin=dict(l=0, r=0, t=40, b=0),
        scene=dict(
            xaxis=dict(showticklabels=False, showgrid=False, zeroline=False),
            yaxis=dict(showticklabels=False, showgrid=False, zeroline=False),
            zaxis=dict(showticklabels=False, showgrid=False, zeroline=False),
        )
    )
    
    fig.write_html(output_path)
    return output_path


def main():
    parser = argparse.ArgumentParser(
        description="Visualize Entity-Event RAG knowledge graphs"
    )
    parser.add_argument(
        "--working-dir", "-w",
        required=True,
        help="Working directory containing the graph files"
    )
    parser.add_argument(
        "--mode", "-m",
        choices=["2d", "3d"],
        default="2d",
        help="Visualization mode (default: 2d)"
    )
    parser.add_argument(
        "--output", "-o",
        help="Output file path (default: knowledge_graph_{mode}.html in working dir)"
    )
    parser.add_argument(
        "--no-open",
        action="store_true",
        help="Don't open the visualization in browser"
    )
    
    args = parser.parse_args()
    
    # Find graph file
    graph_path = os.path.join(args.working_dir, "graph_chunk_entity_relation.graphml")
    if not os.path.exists(graph_path):
        print(f"Error: No graph file found at {graph_path}")
        print("You need to process documents first to generate the knowledge graph.")
        sys.exit(1)
    
    # Load graph
    print(f"Loading graph from {graph_path}...")
    G = nx.read_graphml(graph_path)
    print(f"Loaded graph with {len(G.nodes())} nodes and {len(G.edges())} edges")
    
    # Set output path
    if args.output:
        output_path = args.output
    else:
        output_path = os.path.join(args.working_dir, f"knowledge_graph_{args.mode}.html")
    
    # Generate visualization
    print(f"Generating {args.mode.upper()} visualization...")
    if args.mode == "2d":
        result_path = visualize_graph_2d(G, output_path)
    else:
        result_path = visualize_graph_3d(G, output_path)
    
    print(f"Visualization saved to: {result_path}")
    
    # Open in browser
    if not args.no_open:
        webbrowser.open(f"file://{os.path.abspath(result_path)}")


if __name__ == "__main__":
    main()
